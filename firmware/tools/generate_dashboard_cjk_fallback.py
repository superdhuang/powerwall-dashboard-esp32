#!/usr/bin/env python3
"""Generate a compact Noto CJK fallback for firmware UI string glyphs."""

import argparse
import hashlib
import re
from pathlib import Path

import freetype
from fontTools.ttLib import TTFont


SIZES = {10: (12, 2), 12: (14, 2), 14: (16, 3), 18: (20, 3), 20: (22, 4), 28: (32, 5)}
ROOT = Path(__file__).resolve().parents[1]
FONT_SOURCE = ROOT / "src/dashboard_cjk_fallback.cpp"
BASE_FONT_SOURCE = ROOT / "src/cjk_fonts.cpp"
UI_SOURCE = ROOT / "src/ui_720x720_lvgl.hpp"


def format_bytes(values):
    return "\n".join(
        "  " + ", ".join(f"0x{value:02x}" for value in values[i:i + 16]) + ","
        for i in range(0, len(values), 16)
    )


def existing_codepoints():
    source = BASE_FONT_SOURCE.read_text()
    match = re.search(r"kCjkEntries_12\[\] = \{(.*?)\n\};", source, re.S)
    if not match:
        raise RuntimeError("could not read the existing CJK glyph table")
    return {int(value, 16) for value in re.findall(r"\{ 0x([0-9A-Fa-f]+)U,", match.group(1))}


def collect_required_codepoints():
    source = UI_SOURCE.read_text() + (ROOT / "src/weekly_history_ui.inc").read_text()
    string_literals = re.findall(r'"((?:[^"\\]|\\.)*)"', source)
    used = {ord(char) for value in string_literals for char in value
            if 0x3400 <= ord(char) <= 0x9FFF}
    # Settings uses this fallback font directly, so it needs every glyph in its labels.
    settings_labels = {ord(char) for char in "顯示亮度音量播放測試音"}
    return sorted((used - existing_codepoints()) | settings_labels)


def rasterize(face, codepoint):
    face.load_char(codepoint, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
    glyph = face.glyph
    bitmap = glyph.bitmap
    if bitmap.pixel_mode != freetype.FT_PIXEL_MODE_GRAY and bitmap.width:
        raise ValueError(f"unsupported pixel mode for U+{codepoint:04X}")
    pixels = []
    for y in range(bitmap.rows):
        row = y * bitmap.pitch if bitmap.pitch >= 0 else (bitmap.rows - 1 - y) * -bitmap.pitch
        pixels.extend((bitmap.buffer[row + x] * 15 + 127) // 255 for x in range(bitmap.width))
    packed = [(pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0)
              for i in range(0, len(pixels), 2)]
    return (round(glyph.advance.x / 64), bitmap.width, bitmap.rows,
            glyph.bitmap_left, glyph.bitmap_top - bitmap.rows, packed)


def generate(font_path):
    codepoints = collect_required_codepoints()
    charmap = TTFont(font_path).getBestCmap()
    missing = [cp for cp in codepoints if cp not in charmap]
    if missing:
        raise RuntimeError("font does not contain: " + "".join(chr(cp) for cp in missing))
    source_hash = hashlib.sha256(font_path.read_bytes()).hexdigest()
    lines = [
        "// Generated by firmware/tools/generate_dashboard_cjk_fallback.py.",
        "// Source: Noto Sans CJK TC Regular; SIL Open Font License 1.1.",
        f"// Source SHA-256: {source_hash}",
        "// License: firmware/licenses/Noto-CJK-OFL.txt",
        '#include "cjk_fonts.hpp"',
        "#include <stddef.h>",
        "",
        "struct DashboardCjkGlyphEntry {",
        "  uint32_t codepoint; uint32_t bitmap_index; uint8_t adv_w; uint8_t box_w;",
        "  uint8_t box_h; int8_t ofs_x; int8_t ofs_y;",
        "};",
        "struct DashboardCjkFontTable {",
        "  const uint8_t* bitmap; const DashboardCjkGlyphEntry* entries; size_t count;",
        "};",
        "static const DashboardCjkGlyphEntry* findDashboardCjkGlyph(const DashboardCjkFontTable* table, uint32_t cp) {",
        "  size_t lo = 0, hi = table->count;",
        "  while (lo < hi) {",
        "    const size_t mid = lo + (hi - lo) / 2;",
        "    if (table->entries[mid].codepoint == cp) return &table->entries[mid];",
        "    if (table->entries[mid].codepoint < cp) lo = mid + 1; else hi = mid;",
        "  }",
        "  return nullptr;",
        "}",
        "static bool dashboardCjkGetDsc(const lv_font_t* font, lv_font_glyph_dsc_t* out, uint32_t cp, uint32_t) {",
        "  const auto* table = static_cast<const DashboardCjkFontTable*>(font->dsc);",
        "  const auto* glyph = findDashboardCjkGlyph(table, cp);",
        "  if (!glyph) return false;",
        "  out->resolved_font = font; out->adv_w = glyph->adv_w; out->box_w = glyph->box_w;",
        "  out->box_h = glyph->box_h; out->ofs_x = glyph->ofs_x; out->ofs_y = glyph->ofs_y;",
        "  out->bpp = 4; out->is_placeholder = 0; return true;",
        "}",
        "static const uint8_t* dashboardCjkGetBitmap(const lv_font_t* font, uint32_t cp) {",
        "  const auto* table = static_cast<const DashboardCjkFontTable*>(font->dsc);",
        "  const auto* glyph = findDashboardCjkGlyph(table, cp);",
        "  return glyph ? &table->bitmap[glyph->bitmap_index] : nullptr;",
        "}",
        "",
    ]
    for size, (line_height, baseline) in SIZES.items():
        face = freetype.Face(str(font_path))
        face.set_pixel_sizes(0, size)
        data, entries = [], []
        glyphs = sorted({ord(char) for char in "住家電網未知"}) if size == 10 else codepoints
        for cp in glyphs:
            advance, width, height, x, y, pixels = rasterize(face, cp)
            if not (0 <= advance <= 255 and 0 <= width <= 255 and 0 <= height <= 255
                    and -128 <= x <= 127 and -128 <= y <= 127):
                raise ValueError(f"glyph metrics out of range for U+{cp:04X} at {size}px")
            entries.append((cp, len(data), advance, width, height, x, y))
            data.extend(pixels)
        lines += [
            f"static const uint8_t kDashboardCjkBitmap_{size}[] = {{",
            format_bytes(data),
            "};",
            f"static const DashboardCjkGlyphEntry kDashboardCjkEntries_{size}[] = {{",
            *(f"  {{ 0x{cp:04X}U, {index}U, {advance}, {width}, {height}, {x}, {y} }},"
              for cp, index, advance, width, height, x, y in entries),
            "};",
            f"static const DashboardCjkFontTable kDashboardCjkTable_{size} = {{",
            f"  kDashboardCjkBitmap_{size}, kDashboardCjkEntries_{size},",
            f"  sizeof(kDashboardCjkEntries_{size}) / sizeof(kDashboardCjkEntries_{size}[0])",
            "};",
            f'extern "C" const lv_font_t font_dashboard_cjk_{size} = {{',
            "  dashboardCjkGetDsc, dashboardCjkGetBitmap,",
            f"  {line_height}, {baseline}, LV_FONT_SUBPX_NONE, -1, 1,",
            f"  &kDashboardCjkTable_{size}, " + ("&lv_font_montserrat_10" if size == 10 else "&lv_font_montserrat_28" if size == 28 else f"&font_universal_sans_{size}"),
            "};",
            "",
        ]
    lines.insert(4, f"// Required extra CJK glyphs: {len(codepoints)}")
    lines.insert(5, "// " + "".join(chr(cp) for cp in codepoints))
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, help="path to NotoSansCJKtc-Regular.otf")
    parser.add_argument("--output", type=Path, default=FONT_SOURCE)
    args = parser.parse_args()
    args.output.write_text(generate(args.font))
