#!/usr/bin/env python3
"""Rasterize the supplied Universal Sans TTF for the LVGL firmware fonts."""

import argparse
import hashlib
from pathlib import Path

import freetype
from fontTools.ttLib import TTFont


SIZES = {12: (14, 2), 14: (16, 3), 18: (20, 3), 20: (22, 4)}
EXTRA_CODEPOINTS = {0x2010, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C,
                    0x201D, 0x2022, 0x2026, 0x20AC}


def format_bytes(values):
    return "\n".join(
        "  " + ", ".join(f"0x{value:02x}" for value in values[i:i + 16]) + ","
        for i in range(0, len(values), 16)
    )


def render_glyph(face, codepoint):
    face.load_char(codepoint, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
    glyph = face.glyph
    bitmap = glyph.bitmap
    if bitmap.pixel_mode != freetype.FT_PIXEL_MODE_GRAY and bitmap.width:
        raise ValueError(f"unsupported pixel mode for U+{codepoint:04X}")
    pixels = []
    for y in range(bitmap.rows):
        row = y * bitmap.pitch if bitmap.pitch >= 0 else (bitmap.rows - 1 - y) * -bitmap.pitch
        pixels.extend((bitmap.buffer[row + x] * 15 + 127) // 255 for x in range(bitmap.width))
    packed = [(pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0)
              for i in range(0, len(pixels), 2)]
    return (round(glyph.advance.x / 64), bitmap.width, bitmap.rows,
            glyph.bitmap_left, glyph.bitmap_top - bitmap.rows, packed)


def generate(font_path):
    cmap = TTFont(font_path).getBestCmap()
    codepoints = sorted(({cp for cp in range(0x20, 0x250)} | EXTRA_CODEPOINTS) & cmap.keys())
    source_hash = hashlib.sha256(font_path.read_bytes()).hexdigest()
    out = [
        "// Generated by firmware/tools/generate_universal_sans_fonts.py.",
        "// Source: UniversalSansText-Medium-540.ttf",
        f"// Source SHA-256: {source_hash}",
        "// Latin glyph subset only; the original TTF is not embedded.",
        '#include "cjk_fonts.hpp"',
        "#include <stddef.h>",
        "",
        "struct UniversalGlyphEntry {",
        "  uint32_t codepoint;",
        "  uint32_t bitmap_index;",
        "  uint8_t adv_w;",
        "  uint8_t box_w;",
        "  uint8_t box_h;",
        "  int8_t ofs_x;",
        "  int8_t ofs_y;",
        "};",
        "",
        "struct UniversalFontTable {",
        "  const uint8_t* bitmap;",
        "  const UniversalGlyphEntry* entries;",
        "  size_t count;",
        "};",
        "",
        "static const UniversalGlyphEntry* findUniversalGlyph(const UniversalFontTable* table, uint32_t letter) {",
        "  size_t lo = 0, hi = table->count;",
        "  while (lo < hi) {",
        "    const size_t mid = lo + (hi - lo) / 2;",
        "    const uint32_t cp = table->entries[mid].codepoint;",
        "    if (cp == letter) return &table->entries[mid];",
        "    if (cp < letter) lo = mid + 1;",
        "    else hi = mid;",
        "  }",
        "  return nullptr;",
        "}",
        "",
        "static bool universalGetGlyphDsc(const lv_font_t* font, lv_font_glyph_dsc_t* out,",
        "                                 uint32_t letter, uint32_t /*next*/) {",
        "  const auto* table = static_cast<const UniversalFontTable*>(font->dsc);",
        "  const auto* glyph = findUniversalGlyph(table, letter);",
        "  if (!glyph) return false;",
        "  out->resolved_font = font;",
        "  out->adv_w = glyph->adv_w;",
        "  out->box_w = glyph->box_w;",
        "  out->box_h = glyph->box_h;",
        "  out->ofs_x = glyph->ofs_x;",
        "  out->ofs_y = glyph->ofs_y;",
        "  out->bpp = 4;",
        "  out->is_placeholder = 0;",
        "  return true;",
        "}",
        "",
        "static const uint8_t* universalGetGlyphBitmap(const lv_font_t* font, uint32_t letter) {",
        "  const auto* table = static_cast<const UniversalFontTable*>(font->dsc);",
        "  const auto* glyph = findUniversalGlyph(table, letter);",
        "  return glyph ? &table->bitmap[glyph->bitmap_index] : nullptr;",
        "}",
        "",
    ]
    for size, (line_height, baseline) in SIZES.items():
        face = freetype.Face(str(font_path))
        face.set_pixel_sizes(0, size)
        bitmap_data = []
        entries = []
        for cp in codepoints:
            adv, width, height, x, y, packed = render_glyph(face, cp)
            if not (0 <= adv <= 255 and 0 <= width <= 255 and 0 <= height <= 255
                    and -128 <= x <= 127 and -128 <= y <= 127):
                raise ValueError(f"glyph metrics out of range for U+{cp:04X} at {size}px")
            entries.append((cp, len(bitmap_data), adv, width, height, x, y))
            bitmap_data.extend(packed)
        out += [
            f"static const uint8_t kUniversalBitmap_{size}[] = {{",
            format_bytes(bitmap_data),
            "};",
            f"static const UniversalGlyphEntry kUniversalEntries_{size}[] = {{",
            *(f"  {{ 0x{cp:04X}U, {index}U, {adv}, {width}, {height}, {x}, {y} }},"
              for cp, index, adv, width, height, x, y in entries),
            "};",
            f"static const UniversalFontTable kUniversalTable_{size} = {{",
            f"  kUniversalBitmap_{size}, kUniversalEntries_{size},",
            f"  sizeof(kUniversalEntries_{size}) / sizeof(kUniversalEntries_{size}[0])",
            "};",
            f'extern "C" const lv_font_t font_universal_sans_{size} = {{',
            "  universalGetGlyphDsc, universalGetGlyphBitmap,",
            f"  {line_height}, {baseline}, LV_FONT_SUBPX_NONE, -1, 1,",
            f"  &kUniversalTable_{size}, &lv_font_montserrat_{size}",
            "};",
            "",
        ]
    return "\n".join(out).rstrip()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, help="path to UniversalSansText-Medium-540.ttf")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "src/universal_sans_fonts.cpp")
    args = parser.parse_args()
    args.output.write_text(generate(args.font) + "\n")
