#!/usr/bin/env python3
"""Package extract_3d_assets_480.py output into a firmware C++ asset file.

Produces the native 469x293 stage symbols used by firmware/src/ui_480:
  * kStageRle_<frame>: 3-byte RLE (count, rgb565 lo, hi); colour 0 = "keep the
    parent frame's pixels", so weather variants are stored as deltas.
  * kStageOffGridXPixels / kStageSoePixels / kStageWirePixels from the *.bin tables.
  * the phase-effects include (moon atlas + solar spans) is #included at the end.

usage: package_stage_assets_480.py --in-dir DIR \
           --phase-inc stage_phase_effects_469x293.inc --out stage_assets_469x293.cpp
"""
import argparse
import os
import struct

import numpy as np
from PIL import Image

# frame -> parent frame (None = full frame). Mirrors decodeStage3DFrame().
FRAMES = [
    ("clear", None), ("partly", "clear"), ("overcast", "clear"),
    ("rain", "overcast"), ("rain_1", "rain"), ("rain_2", "rain"),
    ("storm", "overcast"), ("storm_1", "storm"), ("storm_2", "storm"),
    ("snow", "overcast"), ("snow_1", "snow"), ("snow_2", "snow"),
    ("wind", "clear"), ("wind_1", "wind"), ("wind_2", "wind"),
    ("sunrise", "clear"), ("sunset", "clear"), ("night", None),
]


def load565(path, w, h):
    rgb = np.asarray(Image.open(path).convert("RGB"), dtype=np.uint32)
    if rgb.shape[:2] != (h, w):
        raise SystemExit(f"{path}: {rgb.shape[1]}x{rgb.shape[0]} != {w}x{h}")
    v = ((rgb[..., 0] >> 3) << 11) | ((rgb[..., 1] >> 2) << 5) | (rgb[..., 2] >> 3)
    v[v == 0] = 1  # 0 is the RLE "skip" marker
    return v.astype(np.uint16).ravel()


def rle(values, parent):
    out = bytearray()
    n = len(values)
    i = 0
    while i < n:
        skip = parent is not None and values[i] == parent[i]
        col = 0 if skip else int(values[i])
        j = i + 1
        while j < n and j - i < 255:
            s2 = parent is not None and values[j] == parent[j]
            if s2 != skip or (not skip and values[j] != values[i]):
                break
            j += 1
        out += bytes((j - i, col & 0xFF, col >> 8))
        i = j
    return out


def c_bytes(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for k in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[k:k + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def read_bin(path, fmt):
    d = open(path, "rb").read()
    n = struct.unpack("<I", d[:4])[0]
    sz = struct.calcsize("<" + fmt)
    return [struct.unpack("<" + fmt, d[4 + i * sz:4 + (i + 1) * sz]) for i in range(n)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in-dir", required=True)
    ap.add_argument("--phase-inc", required=True, help="include name emitted at the end of the file")
    ap.add_argument("--out", required=True)
    ap.add_argument("--source", default="", help="provenance note for the header comment")
    a = ap.parse_args()
    w, h = 469, 293

    frames = {name: load565(os.path.join(a.in_dir, f"stage_{name}.png"), w, h) for name, _ in FRAMES}

    offx = read_bin(os.path.join(a.in_dir, "offgridx_3d.bin"), "HHBBB")
    soe = read_bin(os.path.join(a.in_dir, "soe_3d.bin"), "HHBBBf")
    wires = read_bin(os.path.join(a.in_dir, "wires_3d.bin"), "HHBfhhh")

    o = [f"// Generated by firmware/tools/package_stage_assets_480.py ({w}x{h}).",
         f"// {a.source}" if a.source else "// Source: extract_3d_assets_480.py output",
         '#include "stage_3d_assets.hpp"', "#include <string.h>", "",
         f"extern const uint16_t kStage3DWidth = {w}U;",
         f"extern const uint16_t kStage3DHeight = {h}U;", "",
         f"const size_t kStageOffGridXPixelCount = {len(offx)}U;",
         "const StageOffGridXPixel kStageOffGridXPixels[] = {"]
    o += [f"  {{{x}U, {y}U, {r}U, {g}U, {b}U}}," for x, y, r, g, b in offx]
    o += ["};", "", f"const size_t kStageSoePixelCount = {len(soe)}U;",
          "const StageSoePixel kStageSoePixels[] = {"]
    o += [f"  {{{x}U, {y}U, {dr}U, {dg}U, {db}U, {fr:.6f}f}}," for x, y, dr, dg, db, fr in soe]
    o += ["};", "", f"const size_t kStageWirePixelCount = {len(wires)}U;",
          "const StageWirePixel kStageWirePixels[] = {"]
    o += [f"  {{{x}U, {y}U, {wid}U, {u:.6f}f, {dr}, {dg}, {db}}}," for x, y, wid, u, dr, dg, db in wires]
    o += ["};", ""]

    total = 0
    for name, parent in FRAMES:
        data = rle(frames[name], frames[parent] if parent else None)
        total += len(data)
        o.append(c_bytes(f"kStageRle_{name}", data))
        o.append("")

    o.append(f"""static void applyRleStream(uint16_t* dst, const uint8_t* rle, size_t rle_len) {{
  size_t pos = 0;
  const size_t max_px = {w}U * {h}U;
  for (size_t i = 0; i + 2 < rle_len && pos < max_px; i += 3) {{
    uint8_t cnt = rle[i];
    uint16_t col = static_cast<uint16_t>(rle[i + 1]) | (static_cast<uint16_t>(rle[i + 2]) << 8);
    if (col == 0U) {{
      pos += cnt;
    }} else {{
      for (uint8_t k = 0; k < cnt && pos < max_px; ++k) {{
        dst[pos++] = col;
      }}
    }}
  }}
}}

#define PW_APPLY(name) applyRleStream(dst_rgb565, kStageRle_##name, sizeof(kStageRle_##name))
bool decodeStage3DFrame(const char* key, uint16_t* dst_rgb565) {{
  if (!key || !dst_rgb565) return false;
  if (strcmp(key, "night") == 0) {{ PW_APPLY(night); return true; }}
  PW_APPLY(clear);
  if (strcmp(key, "clear") == 0) return true;
  if (strcmp(key, "partly") == 0) {{ PW_APPLY(partly); return true; }}
  if (strcmp(key, "sunrise") == 0) {{ PW_APPLY(sunrise); return true; }}
  if (strcmp(key, "sunset") == 0) {{ PW_APPLY(sunset); return true; }}
  if (strncmp(key, "wind", 4) == 0) {{
    PW_APPLY(wind);
    if (strcmp(key, "wind_1") == 0) PW_APPLY(wind_1);
    else if (strcmp(key, "wind_2") == 0) PW_APPLY(wind_2);
    return true;
  }}
  PW_APPLY(overcast);
  if (strcmp(key, "overcast") == 0) return true;
  if (strncmp(key, "rain", 4) == 0) {{
    PW_APPLY(rain);
    if (strcmp(key, "rain_1") == 0) PW_APPLY(rain_1);
    else if (strcmp(key, "rain_2") == 0) PW_APPLY(rain_2);
    return true;
  }}
  if (strncmp(key, "storm", 5) == 0) {{
    PW_APPLY(storm);
    if (strcmp(key, "storm_1") == 0) PW_APPLY(storm_1);
    else if (strcmp(key, "storm_2") == 0) PW_APPLY(storm_2);
    return true;
  }}
  if (strncmp(key, "snow", 4) == 0) {{
    PW_APPLY(snow);
    if (strcmp(key, "snow_1") == 0) PW_APPLY(snow_1);
    else if (strcmp(key, "snow_2") == 0) PW_APPLY(snow_2);
    return true;
  }}
  return true;
}}
#undef PW_APPLY

#include "{a.phase_inc}"
""")
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(o))
    print(f"{a.out}: {total} RLE bytes, offgridx={len(offx)} soe={len(soe)} wires={len(wires)}")


if __name__ == "__main__":
    main()
