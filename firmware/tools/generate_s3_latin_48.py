#!/usr/bin/env python3
"""Keep LVGL's exact 48px Latin raster/kerning, omit unused FontAwesome icons."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / '.pio/libdeps/waveshare-esp32s3-touch-lcd-4b/lvgl/src/font/lv_font_montserrat_48.c'
s = source.read_text()
dsc = re.search(r'(static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc\[\] = \{)(.*?)(\n\};)', s, re.S)
entries = re.findall(r'\{\.bitmap_index = .*?\}', dsc[2])
assert len(entries) == 158
end = int(re.search(r'bitmap_index = (\d+)', entries[98])[1])
bitmap = re.search(r'(static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap\[\] = \{)(.*?)(\n\};)', s, re.S)
raw = re.findall(r'0x[0-9a-fA-F]+', re.sub(r'/\*.*?\*/', '', bitmap[2], flags=re.S))
assert end == 36130
original_bytes = len(raw)
raw = raw[:end]
s = s[:bitmap.start(2)] + '\n' + '\n'.join('    ' + ', '.join(raw[i:i+16]) + ',' for i in range(0, end, 16)) + s[bitmap.end(2):]
s = re.sub(r'(static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc\[\] = \{).*?(\n\};)', lambda m: m[1]+'\n'+',\n'.join('    '+x for x in entries[:98])+m[2], s, flags=re.S)
s = re.sub(r'(static const uint16_t unicode_list_1\[\] = \{).*?(\n\};)', r'\1\n    0x0, 0x1f72\2', s, flags=re.S)
s = s.replace('.range_length = 63475', '.range_length = 8051').replace('.list_length = 62', '.list_length = 2')
s = s.replace('#ifdef LV_LVGL_H_INCLUDE_SIMPLE\n    #include "lvgl.h"\n#else\n    #include "../../lvgl.h"\n#endif', '#include "cjk_fonts.hpp"')
s = s.replace('#if LV_FONT_MONTSERRAT_48', '#if defined(POWERWALL_WAVESHARE_S3_LCD_4B) || defined(POWERWALL_S3_LATIN_FONT)')
s = s.replace('const lv_font_t lv_font_montserrat_48 =', 'extern "C" const lv_font_t font_s3_latin_48 =')
license = (source.parents[2] / 'LICENCE.txt').read_text()
s = '// Generated by firmware/tools/generate_s3_latin_48.py; same Latin glyph pixels and kerning.\n/*\n'+license+'*/\n'+s
(root/'src/s3_latin_48.cpp').write_text(s)
print(f'48px bitmap: {original_bytes} -> {end} bytes; retained ASCII, degree, bullet, original metrics/kerning')
