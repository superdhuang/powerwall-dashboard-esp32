#!/usr/bin/env python3
"""Generate the small CJK subset used by the 480px home dashboard."""

import argparse
import hashlib
from pathlib import Path

import freetype
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/dashboard_home_cjk.cpp"
CHARS_24 = ("尖峰離峰費率備援週間週末小時分鐘天日後剩餘目前電量充電放電高峰時段未知正在連接等待設定已線"
            "今日自給率池壓待機中狀態保留自動模式我消耗輸入密碼手機同開啟預估可用時間")
CHARS_33 = "正在連接等待設定已線我的家取得資料天氣無法重試請手機同後開啟輸入密碼失敗檢查"
SIZES = {
    24: (28, 4, "lv_font_montserrat_24", CHARS_24),
    30: (34, 5, "lv_font_montserrat_24", CHARS_24 + "0123456789:-"),
    33: (37, 5, "lv_font_montserrat_32", CHARS_33),
    40: (44, 6, "lv_font_montserrat_40", "孤島供電我的家"),
}


def pack_gray(bitmap):
    pixels = []
    for y in range(bitmap.rows):
        row = y * bitmap.pitch if bitmap.pitch >= 0 else (bitmap.rows - 1 - y) * -bitmap.pitch
        pixels.extend((bitmap.buffer[row + x] * 15 + 127) // 255
                      for x in range(bitmap.width))
    return [(pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0)
            for i in range(0, len(pixels), 2)]


def bytes_literal(values):
    return "\n".join(
        "  " + ", ".join(f"0x{value:02x}" for value in values[i:i + 16]) + ","
        for i in range(0, len(values), 16)
    )


def generate(font_path):
    cps = sorted({ord(c) for _, _, _, chars in SIZES.values() for c in chars})
    cmap = TTFont(str(font_path), fontNumber=0).getBestCmap()
    missing = [cp for cp in cps if cp not in cmap]
    if missing:
        raise RuntimeError("font lacks glyphs: " + "".join(chr(cp) for cp in missing))
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()
    out = [
        "// Generated by firmware/tools/generate_dashboard_home_cjk.py.",
        f"// Source: {font_path.name}; collection face 0.",
        f"// Source SHA-256: {digest}",
        "// Embedded CJK subset only; Latin glyphs use the Montserrat fallback.",
        '#include "cjk_fonts.hpp"',
        "#include <stddef.h>",
        "",
        "struct HomeCjkGlyphEntry { uint32_t codepoint, bitmap_index; uint8_t adv_w, box_w, box_h; int8_t ofs_x, ofs_y; };",
        "struct HomeCjkFontTable { const uint8_t* bitmap; const HomeCjkGlyphEntry* entries; size_t count; };",
        "static const HomeCjkGlyphEntry* findHomeCjkGlyph(const HomeCjkFontTable* table, uint32_t cp) {",
        "  size_t lo = 0, hi = table->count;",
        "  while (lo < hi) { const size_t mid = lo + (hi - lo) / 2; const uint32_t value = table->entries[mid].codepoint;",
        "    if (value == cp) return &table->entries[mid]; if (value < cp) lo = mid + 1; else hi = mid;",
        "  } return nullptr;",
        "}",
        "static bool homeCjkGetDsc(const lv_font_t* font, lv_font_glyph_dsc_t* out, uint32_t cp, uint32_t) {",
        "  const auto* table = static_cast<const HomeCjkFontTable*>(font->dsc); const auto* glyph = findHomeCjkGlyph(table, cp);",
        "  if (!glyph) return false; out->resolved_font = font; out->adv_w = glyph->adv_w; out->box_w = glyph->box_w;",
        "  out->box_h = glyph->box_h; out->ofs_x = glyph->ofs_x; out->ofs_y = glyph->ofs_y; out->bpp = 4; out->is_placeholder = 0; return true;",
        "}",
        "static const uint8_t* homeCjkGetBitmap(const lv_font_t* font, uint32_t cp) {",
        "  const auto* table = static_cast<const HomeCjkFontTable*>(font->dsc); const auto* glyph = findHomeCjkGlyph(table, cp);",
        "  return glyph ? &table->bitmap[glyph->bitmap_index] : nullptr;",
        "}",
        "",
    ]
    for size, (line_height, baseline, fallback, chars) in SIZES.items():
        face = freetype.Face(str(font_path), index=0)
        face.set_pixel_sizes(0, size)
        bitmap_data, entries = [], []
        for cp in sorted({ord(c) for c in chars}):
            face.load_char(cp, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
            glyph, bitmap = face.glyph, face.glyph.bitmap
            if bitmap.pixel_mode != freetype.FT_PIXEL_MODE_GRAY and bitmap.width:
                raise RuntimeError(f"unsupported bitmap mode for U+{cp:04X}")
            advance = round(glyph.advance.x / 64)
            x, y = glyph.bitmap_left, glyph.bitmap_top - bitmap.rows
            if not (0 <= advance <= 255 and bitmap.width <= 255 and bitmap.rows <= 255
                    and -128 <= x <= 127 and -128 <= y <= 127):
                raise RuntimeError(f"glyph metrics out of range for U+{cp:04X} at {size}px")
            entries.append((cp, len(bitmap_data), advance, bitmap.width, bitmap.rows, x, y))
            bitmap_data.extend(pack_gray(bitmap))
        out += [
            f"static const uint8_t kHomeCjkBitmap_{size}[] = {{",
            bytes_literal(bitmap_data), "};",
            f"static const HomeCjkGlyphEntry kHomeCjkEntries_{size}[] = {{",
            *(f"  {{ 0x{cp:04X}U, {index}U, {advance}, {width}, {height}, {x}, {y} }},"
              for cp, index, advance, width, height, x, y in entries),
            "};",
            f"static const HomeCjkFontTable kHomeCjkTable_{size} = {{ kHomeCjkBitmap_{size}, kHomeCjkEntries_{size},",
            f"  sizeof(kHomeCjkEntries_{size}) / sizeof(kHomeCjkEntries_{size}[0]) }};",
            f'extern "C" const lv_font_t font_home_cjk_{size} = {{ homeCjkGetDsc, homeCjkGetBitmap,',
            f"  {line_height}, {baseline}, LV_FONT_SUBPX_NONE, -1, 1, &kHomeCjkTable_{size}, "
            + (f"&{fallback}" if fallback else "nullptr") + " };",
            "",
        ]
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path,
                        default=Path("/System/Library/Fonts/STHeiti Medium.ttc"), nargs="?")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    args.output.write_text(generate(args.font))
